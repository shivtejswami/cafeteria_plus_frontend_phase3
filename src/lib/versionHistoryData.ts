export function getVersionComparison(reportId: string, versionA: number, versionB: number): VersionComparisonData | null {
  const snapshots = versionSnapshots[reportId];
  if (!snapshots) return null;

  const a = snapshots.find(s => s.version === versionA);
  const b = snapshots.find(s => s.version === versionB);
  if (!a || !b || a.version === b.version) return null;

  const keyDifferences: string[] = [];

  if (a.responseCount !== b.responseCount) {
    const diff = b.responseCount - a.responseCount;
    keyDifferences.push(diff > 0
      ? `${diff} more responses in v${b.version} (${b.responseCount} vs ${a.responseCount})`
      : `${Math.abs(diff)} fewer responses in v${b.version} (${b.responseCount} vs ${a.responseCount})`);
  }

  if (a.overallSatisfaction !== b.overallSatisfaction) {
    const diff = b.overallSatisfaction - a.overallSatisfaction;
    keyDifferences.push(diff > 0
      ? `Overall satisfaction +${diff}pts in v${b.version} (${b.overallSatisfaction} vs ${a.overallSatisfaction})`
      : `Overall satisfaction ${diff}pts in v${b.version} (${b.overallSatisfaction} vs ${a.overallSatisfaction})`);
  }

  a.concepts.forEach((ca, i) => {
    const cb = b.concepts[i];
    if (cb && ca.score !== cb.score) {
      const diff = cb.score - ca.score;
      const label = diff > 0 ? `+${diff}` : `${diff}`;
      keyDifferences.push(`${ca.concept}: ${label}pts (v${b.version}: ${cb.score} vs v${a.version}: ${ca.score})`);
    }
  });

  if (a.isSmallSample !== b.isSmallSample) {
    keyDifferences.push(b.isSmallSample
      ? `v${b.version} marked as small sample — v${a.version} was not`
      : `v${b.version} no longer marked as small sample`);
  }

  return { versionA: a, versionB: b, keyDifferences };
}